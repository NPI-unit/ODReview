"""Write requirements-lock-macos.txt: every package requirements.txt needs,
with the exact versions installed in this (working, tested) environment.

    ./.venv/bin/python tools/make_lock.py

Only the dependency closure of requirements.txt is written — not whatever
else happens to sit in the venv (test tools, the old PySide6 add-ons, …).
install.command installs from this file, so every Mac gets the versions the
tests ran against.
"""

from __future__ import annotations

import platform
import sys
from importlib import metadata
from pathlib import Path

from pip._vendor.packaging.markers import default_environment
from pip._vendor.packaging.requirements import Requirement
from pip._vendor.packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "requirements-lock-macos.txt"


def top_level() -> list[Requirement]:
    reqs = []
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            reqs.append(Requirement(line))
    return reqs


def closure(reqs: list[Requirement]) -> dict[str, str]:
    env = default_environment()
    seen: dict[str, str] = {}
    todo = list(reqs)
    while todo:
        r = todo.pop()
        if r.marker is not None and not r.marker.evaluate({**env, "extra": ""}):
            continue
        name = canonicalize_name(r.name)
        if name in seen:
            continue
        try:
            dist = metadata.distribution(r.name)
        except metadata.PackageNotFoundError:
            raise SystemExit(f"{r.name} is required but not installed in this venv")
        if r.specifier and not r.specifier.contains(dist.version, prereleases=True):
            raise SystemExit(f"{r.name} {dist.version} does not satisfy {r.specifier}")
        seen[name] = dist.version
        for dep in dist.requires or []:
            d = Requirement(dep)
            if d.marker is not None and not d.marker.evaluate({**env, "extra": ""}):
                continue
            todo.append(d)
    return seen


def main() -> int:
    pins = closure(top_level())
    lines = [
        "# ErysReview — exact versions for macOS (generated by tools/make_lock.py).",
        f"# From a tested environment: Python {platform.python_version()}, "
        f"{platform.system()} {platform.machine()}. Do not edit by hand.",
        "",
        *[f"{n}=={v}" for n, v in sorted(pins.items())],
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.name}: {len(pins)} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
